function normalizeAppData(data) {
    if (!data || typeof data !== 'object' || !data.lists) return createDefaultData();
    const lists = Object.create(null);
    Object.entries(data.lists).forEach(([id, list]) => {
        if (!list) return;
        lists[id] = {
            name: list.name || 'Sans nom',
            category: list.category || 'Général',
            spinDuration: Number(list.spinDuration) || 4.0,
            confettiIntensity: Number(list.confettiIntensity) || 120,
            minSpins: Number(list.minSpins) || 6,
            eliminationMode: Boolean(list.eliminationMode),
            soundEnabled: list.soundEnabled !== false,
            showPercentages: list.showPercentages !== false,
            visibleOnMain: list.visibleOnMain ?? true,
            items: Array.isArray(list.items) ? list.items.map((item, idx) => ({
                id: item.id || idx,
                name: item.name || 'Option',
                color: item.color || '#3b82f6',
                weight: Number.isFinite(Number(item.weight)) ? Math.max(0, Number(item.weight)) : 10
            })) : []
        };
    });
    if (Object.keys(lists).length === 0) return createDefaultData();
    const activeListId = lists[data.activeListId] ? data.activeListId : Object.keys(lists)[0];
    return {
        activeListId,
        lists,
        recentResults: Array.isArray(data.recentResults) ? data.recentResults.slice(0, 15) : [],
        language: data.language || 'fr'
    };
}

