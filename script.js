function spinWheel(listId) {
    if (spinningWheels[listId]) return;
    const list = appData.lists[listId], items = list.items;
    const total = items.reduce((s, i) => s + i.weight, 0);
    if (!items.length || total <= 0) return toast('Ajoutez au moins une option avec un poids > 0');

    appData.activeListId = listId;
    spinningWheels[listId] = true;
    const card = document.getElementById(`canvas_${listId}`).closest('.wheel-card-item');
    const btn = card.querySelector('.spin-btn'), pointer = card.querySelector('.wheel-pointer');
    btn.disabled = true;

    let r = Math.random() * total, win = 0, start = 0, acc = 0;
    for (let i = 0; i < items.length; i++) {
        if (r < acc + items[i].weight) { win = i; start = acc; break; }
        acc += items[i].weight;
    }
    const slice = items[win].weight / total * TAU;
    const jitter = (Math.random() - 0.5) * slice * 0.7;
    const target = -Math.PI / 2 - (start / total * TAU + slice / 2 + jitter);
    const from = wheelAngles[listId] || 0;
    const to = from + TAU * list.minSpins + mod(target - from, TAU);
    const duration = reduceMotion() ? 600 : list.spinDuration * 1000;
    let t0 = null, lastIdx = sliceAt(items, from);

    function step(ts) {
        if (!t0) t0 = ts;
        const p = Math.min((ts - t0) / duration, 1);
        const ang = from + (to - from) * (1 - Math.pow(1 - p, 4));
        wheelAngles[listId] = ang;
        drawWheel(listId, ang, Math.floor((ts - t0) / 140) % 2);
        const idx = sliceAt(items, ang);
        if (idx !== lastIdx) {
            lastIdx = idx; playTick();
            pointer.animate([{ transform: 'translateX(-50%) rotate(0)' }, { transform: 'translateX(-50%) rotate(-20deg)' }, { transform: 'translateX(-50%) rotate(0)' }], { duration: 110 });
        }
        if (p < 1) return requestAnimationFrame(step);

        spinningWheels[listId] = false;
        wheelAngles[listId] = to % TAU;
        drawWheel(listId, wheelAngles[listId]);
        btn.disabled = false;
        showWinner(listId, win);
    }
    requestAnimationFrame(step);
}

