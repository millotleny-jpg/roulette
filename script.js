function playTick() {
    if (!getCurrentList().soundEnabled) return;
    if (!audioCtx) audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    const o = audioCtx.createOscillator(), g = audioCtx.createGain(), t = audioCtx.currentTime;
    o.type = 'triangle'; o.frequency.value = 900;
    g.gain.setValueAtTime(0.05, t); g.gain.exponentialRampToValueAtTime(0.001, t + 0.05);
    o.connect(g); g.connect(audioCtx.destination); o.start(t); o.stop(t + 0.06);
}

function sliceAt(items, angle) {
    const total = items.reduce((s, i) => s + i.weight, 0);
    let r = mod(-Math.PI / 2 - angle, TAU) / TAU * total, acc = 0;
    for (let i = 0; i < items.length; i++) { acc += items[i].weight; if (r < acc) return i; }
    return items.length - 1;
}

function drawWheel(listId, angle = 0, phase = 0) {
    const canvas = document.getElementById(`canvas_${listId}`);
    if (!canvas) return;
    const px = Math.round((canvas.clientWidth || 340) * (window.devicePixelRatio || 1));
    if (canvas.width !== px) { canvas.width = px; canvas.height = px; }
    const ctx = canvas.getContext('2d');
    ctx.setTransform(px / 340, 0, 0, px / 340, 0, 0);
    ctx.clearRect(0, 0, 340, 340);

    const list = appData.lists[listId], items = list.items;
    const total = items.reduce((s, i) => s + i.weight, 0);
    const c = 170, R = 144;

    ctx.beginPath(); ctx.arc(c, c, 168, 0, TAU); ctx.fillStyle = '#2a1d14'; ctx.fill();
    ctx.lineWidth = 3; ctx.strokeStyle = '#ffc94a'; ctx.stroke();
    for (let i = 0; i < 24; i++) {
        const a = i / 24 * TAU, lit = (i + phase) % 2 === 0;
        ctx.beginPath(); ctx.arc(c + Math.cos(a) * 157, c + Math.sin(a) * 157, 5, 0, TAU);
        ctx.fillStyle = lit ? '#ffe08a' : '#6b4f2a';
        ctx.shadowColor = lit ? '#ffc94a' : 'transparent'; ctx.shadowBlur = lit ? 10 : 0;
        ctx.fill(); ctx.shadowBlur = 0;
    }
    if (!items.length || total <= 0) {
        ctx.beginPath(); ctx.arc(c, c, R, 0, TAU); ctx.fillStyle = '#191423'; ctx.fill();
        ctx.fillStyle = '#a199b0'; ctx.font = '600 15px system-ui'; ctx.textAlign = 'center';
        ctx.fillText('Ajoutez des options', c, c + 5);
        return;
    }

    let a0 = angle;
    items.forEach(item => {
        const slice = item.weight / total * TAU;
        if (slice <= 0) return;
        ctx.beginPath(); ctx.moveTo(c, c); ctx.arc(c, c, R, a0, a0 + slice); ctx.closePath();
        ctx.fillStyle = item.color; ctx.fill();
        ctx.lineWidth = 2; ctx.strokeStyle = '#191423'; ctx.stroke();

        ctx.save(); ctx.translate(c, c); ctx.rotate(a0 + slice / 2);
        ctx.textAlign = 'right'; ctx.textBaseline = 'middle';
        ctx.fillStyle = lum(item.color) > 0.6 ? '#1a1205' : '#fff';
        ctx.font = '700 14px "Bricolage Grotesque", system-ui, sans-serif';
        let label = item.name;
        if (list.showPercentages) label += ` ${Math.round(item.weight / total * 100)}%`;
        const maxW = R - 52;
        while (label.length > 3 && ctx.measureText(label).width > maxW) label = label.slice(0, -2).trimEnd() + '…';
        ctx.fillText(label, R - 14, 0);
        ctx.restore();
        a0 += slice;
    });

    ctx.beginPath(); ctx.arc(c, c, 24, 0, TAU);
    ctx.fillStyle = '#191423'; ctx.fill(); ctx.lineWidth = 5; ctx.strokeStyle = '#ffc94a'; ctx.stroke();
}

