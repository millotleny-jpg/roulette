const PALETTE = ['#ff5d73', '#ffc94a', '#3ddc97', '#4cc9f0', '#a78bfa', '#ff8fab', '#fb923c', '#2dd4bf'];

function addFromText(text) {
    const list = getCurrentList();
    let n = 0;
    text.split(/[,;\n]/).forEach(part => {
        const [nm, w] = part.split(':');
        const name = (nm || '').trim();
        if (!name) return;
        const weight = parseFloat(w);
        list.items.push({ id: Date.now() + Math.random(), name, color: PALETTE[list.items.length % PALETTE.length], weight: isNaN(weight) ? 10 : Math.max(0, weight) });
        n++;
    });
    if (n) { saveAppData(); renderItemsTable(); renderActivePreview(); }
    return n;
}

