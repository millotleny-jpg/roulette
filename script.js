// --- TRADUCTION RÉCURSIVE UNIVERSELLE ---
function applyRecursiveTranslations(root = document.body) {
    const lang = appData.language || 'fr';
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.fr;

    // Fonction récursive interne parcourant tous les nœuds enfants et attributs
    function traverse(node) {
        if (node.nodeType === Node.ELEMENT_NODE) {
            // Traitement direct si l'élément possède l'attribut i18n
            if (node.hasAttribute('data-i18n')) {
                const key = node.getAttribute('data-i18n');
                if (dict[key]) node.textContent = dict[key];
            }
            // Traitement des placeholders i18n
            if (node.hasAttribute('data-i18n-placeholder')) {
                const key = node.getAttribute('data-i18n-placeholder');
                if (dict[key]) node.placeholder = dict[key];
            }
            // Appel récursif sur les enfants
            for (let i = 0; i < node.childNodes.length; i++) {
                traverse(node.childNodes[i]);
            }
        }
    }

    traverse(root);
}

